import csv
import urllib.request
from pathlib import Path

folder = Path(__file__).resolve().parent if "__file__" in globals() else Path.cwd()
raw_file = folder / "vehicles.csv"
trimmed_file = folder / "trimmed_vehicles.csv"

headers = [
    "id", "year", "make", "model", "cylinders", "VClass",
    "city08", "highway08", "comb08", "fuelType", "atvType",
    "co2", "displ", "trany", "drive"
]


def download_dataset():
    url = "https://www.fueleconomy.gov/feg/epadata/vehicles.csv"
    print("Downloading vehicles.csv from fueleconomy.gov... This may take a minute.")
    urllib.request.urlretrieve(url, raw_file)
    print("Download complete!")


def trim_vehicle_data():
    with open(raw_file, "r", newline="", encoding="utf-8-sig") as infile:
        reader = csv.DictReader(infile)
        with open(trimmed_file, "w", newline="", encoding="utf-8") as outfile:
            writer = csv.DictWriter(outfile, fieldnames=headers)
            writer.writeheader()
            for row in reader:
                writer.writerow({name: row.get(name, "") for name in headers})


def load_vehicle_data():
    vehicles = []
    with open(trimmed_file, "r", newline="", encoding="utf-8-sig") as file:
        reader = csv.DictReader(file)
        for row in reader:
            try:
                row["year"] = int(row["year"])
                row["city08"] = float(row["city08"])
                row["highway08"] = float(row["highway08"])
                row["comb08"] = float(row["comb08"])
                row["co2"] = float(row["co2"]) if row["co2"] else None
                row["displ"] = float(row["displ"]) if row["displ"] else None
                row["cylinders"] = int(row["cylinders"]) if row["cylinders"] else None
                vehicles.append(row)
            except (ValueError, TypeError):
                continue
    return vehicles


def filter_by_year(vehicles, year):
    return [car for car in vehicles if car["year"] == year]


def filter_by_maker(vehicles, maker):
    return [car for car in vehicles if car["make"].lower() == maker.lower()]


def compute_avg_mpg(vehicles):
    if not vehicles:
        print("No vehicles found.")
        return

    avg_city = sum(car["city08"] for car in vehicles) / len(vehicles)
    avg_highway = sum(car["highway08"] for car in vehicles) / len(vehicles)
    print(f"Average city MPG: {avg_city:.2f}")
    print(f"Average highway MPG: {avg_highway:.2f}")


def show_vehicles(vehicles):
    for car in vehicles:
        print(f'{car["year"]} {car["make"]} {car["model"]} - '
              f'City: {car["city08"]:g}, Highway: {car["highway08"]:g}, '
              f'Combined: {car["comb08"]:g}')


def top5_cleanest(vehicles):
    valid = [car for car in vehicles if car["comb08"] > 0]
    top = sorted(valid, key=lambda car: car["comb08"], reverse=True)[:5]
    print("\nTop 5 most fuel-efficient vehicles:")
    if top:
        show_vehicles(top)
    else:
        print("No vehicles found.")


def bottom5_dirtiest(vehicles):
    valid = [car for car in vehicles if car["comb08"] > 0]
    bottom = sorted(valid, key=lambda car: car["comb08"])[:5]
    print("\nBottom 5 least fuel-efficient vehicles:")
    if bottom:
        show_vehicles(bottom)
    else:
        print("No vehicles found.")


def display_menu():
    print("\n1. View total vehicle count")
    print("2. View fuel efficiency statistics")
    print("3. Search vehicles by manufacturer")
    print("4. Exit")


def main():
    try:
        if not raw_file.exists():
            download_dataset()
        if not trimmed_file.exists():
            trim_vehicle_data()
        vehicles = load_vehicle_data()
    except (FileNotFoundError, OSError, urllib.error.URLError) as error:
        print("Could not prepare the dataset:", error)
        print("Please verify your internet connection or dataset source.")
        return

    if not vehicles:
        print("No valid vehicle data was found.")
        return

    print("Total vehicles in dataset:", len(vehicles))
    years = [car["year"] for car in vehicles]
    print("Years available:", min(years), "to", max(years))

    while True:
        year_text = input("\nWhich year are you interested in: ").strip()
        try:
            year = int(year_text)
        except ValueError:
            print("Please enter a valid year, such as 2023.")
            continue

        selected = filter_by_year(vehicles, year)
        if selected:
            break
        print("No vehicles found for that year. Try again.")

    while True:
        display_menu()
        choice = input("Choose an option (1-4): ").strip()

        if choice == "1":
            print(f"Total vehicle records for {year}: {len(selected)}")

        elif choice == "2":
            print("\n1. Average city and highway MPG")
            print("2. Top 5 most fuel-efficient vehicles")
            print("3. Bottom 5 least fuel-efficient vehicles")
            option = input("Choose an option (1-3): ").strip()
            if option == "1":
                compute_avg_mpg(selected)
            elif option == "2":
                top5_cleanest(selected)
            elif option == "3":
                bottom5_dirtiest(selected)
            else:
                print("Invalid option. Choose 1, 2, or 3.")

        elif choice == "3":
            maker = input("Enter manufacturer name: ").strip()
            matches = filter_by_maker(selected, maker)
            if matches:
                print(f"Found {len(matches)} records for {maker} in {year}:")
                show_vehicles(matches)
            else:
                print("No vehicles found for that manufacturer and year.")

        elif choice == "4":
            print("Goodbye!")
            break

        else:
            print("Invalid option. Choose 1, 2, 3, or 4.")


if __name__ == "__main__":
    try:
        main()
    except (KeyboardInterrupt, EOFError):
        print("\nProgram stopped.")